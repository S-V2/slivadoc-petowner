export function translateCopy(value: string, language: AppLanguage) {
  if (language === "id" || !value) return value;
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const core = value.trim();
  if (!core) return value;
  return `${leading}${translateDynamic(core, language)}${trailing}`;
}

function translateNode(node: ReactNode, language: AppLanguage): ReactNode {
  if (typeof node === "string") return translateCopy(node, language);
  if (Array.isArray(node)) return node.map((child) => translateNode(child, language));
  return node;
}

type I18nContextValue = {
  language: AppLanguage;
  locale: string;
  setLanguage: (language: AppLanguage) => Promise<void>;
  t: (value: string) => string;
  formatCurrency: (value: number) => string;
  formatDate: (value: Date | string | number, options?: Intl.DateTimeFormatOptions) => string;
  formatNumber: (value: number) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function LanguageProvider({ children }: PropsWithChildren) {
  const [language, setLanguageState] = useState<AppLanguage>("id");

  useEffect(() => {
    let active = true;
    void SecureStore.getItemAsync(LANGUAGE_KEY)
      .then((stored) => {
        if (active && (stored === "id" || stored === "en" || stored === "zh")) {
          setLanguageState(stored);
        }
      })
      .catch(() => undefined);
    return () => {
      active = false;
    };
  }, []);

  const setLanguage = useCallback(async (nextLanguage: AppLanguage) => {
    setLanguageState(nextLanguage);
    try {
      await SecureStore.setItemAsync(LANGUAGE_KEY, nextLanguage);
    } catch {
      // The in-memory preference still applies for the active session.
    }
  }, []);

  const value = useMemo<I18nContextValue>(() => {
    const locale = localeByLanguage[language];
    return {
      language,
      locale,
      setLanguage,
      t: (text) => translateCopy(text, language),
      formatCurrency: (amount) =>
        new Intl.NumberFormat(locale, {
          style: "currency",
          currency: "IDR",
          maximumFractionDigits: 0,
        }).format(Number.isFinite(amount) ? amount : 0),
      formatDate: (date, options) => {
        const parsed = date instanceof Date ? date : new Date(date);
        if (Number.isNaN(parsed.getTime())) return "—";
        return new Intl.DateTimeFormat(locale, options).format(parsed);
      },
      formatNumber: (number) =>
        new Intl.NumberFormat(locale).format(Number.isFinite(number) ? number : 0),
    };
  }, [language, setLanguage]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used inside LanguageProvider");
  return context;
}

export function LocalizedText({ children, accessibilityLabel, ...props }: TextProps) {
  const { language, t } = useI18n();
  return (
    <NativeText
      {...props}
      accessibilityLabel={accessibilityLabel ? t(accessibilityLabel) : undefined}
    >
      {translateNode(children, language)}
    </NativeText>
  );
}

export function LocalizedTextInput({ placeholder, accessibilityLabel, ...props }: TextInputProps) {
  const { t } = useI18n();
  return (
    <NativeTextInput
      {...props}
      accessibilityLabel={accessibilityLabel ? t(accessibilityLabel) : undefined}
      placeholder={placeholder ? t(placeholder) : undefined}
    />
  );
}
