import { readFile, writeFile, mkdir } from "node:fs/promises";
import { createHash } from "node:crypto";

const source = new URL("../../slivadoc-backend/migrations/20260825100000_indonesia_regions_2025.sql", import.meta.url);
const sql = await readFile(source, "utf8");
const out = new URL("../app/data/regions/", import.meta.url);
await mkdir(out, { recursive: true });
const rows = [...sql.matchAll(/^\('([\d.]+)'(?:,'([\d.]+)')?,'((?:''|[^'])*)'\)[,;]?$/gm)]
  .map(([, code, parent, name]) => ({ code, parent: parent || "", name: name.replaceAll("''", "'") }));
const codes = new Set(rows.map((r) => r.code));
if (codes.size !== rows.length || rows.some((r) => r.parent && !codes.has(r.parent))) throw new Error("Invalid region hierarchy");
const counts = Object.fromEntries([2, 5, 8, 13].map((length) => [length, rows.filter((r) => r.code.length === length).length]));
if (counts[2] !== 38 || counts[5] !== 514 || counts[8] < 7000 || counts[13] < 80000) throw new Error(`Incomplete snapshot: ${JSON.stringify(counts)}`);
await writeFile(new URL("index.json", out), JSON.stringify(rows.filter((r) => r.code.length <= 5)) + "\n");
const provinces = rows.filter((r) => r.code.length === 2);
for (const province of provinces) {
  await writeFile(new URL(`${province.code}.json`, out), JSON.stringify(rows.filter((r) => r.code.startsWith(province.code + ".") && r.code.length > 5)) + "\n");
}
await writeFile(new URL("loaders.ts", out), `// Generated by scripts/build-seo-regions.mjs; server-only lazy province shards.\nexport const regionLoaders = {\n${provinces.map((r) => `  "${r.code}": () => import("./${r.code}.json", { with: { type: "json" } }).then((m) => m.default),`).join("\n")}\n};\n`);
await writeFile(new URL("source.json", out), JSON.stringify({ source: "https://github.com/cahyadsn/wilayah", license: "MIT", regulation: "Kepmendagri No. 300.2.2-2430 Tahun 2025", sourceRevision: "2026-02-13", generatedOn: "2026-10-07", sha256: createHash("sha256").update(sql).digest("hex"), counts: { provinces: counts[2], regencies: counts[5], districts: counts[8], villages: counts[13] }, total: rows.length }, null, 2) + "\n");
console.log(JSON.stringify({ counts, total: rows.length }));
